"""Writing results to outputs/<period>/<name>/results.md, with charts and a trade list.

Only numbers and facts go in these files. What they MEAN is written by hand
in the README ("Results", "Why it might not work", "Limitations").
"""
from __future__ import annotations

import datetime as dt
import hashlib
from pathlib import Path

import pandas as pd

from .data import DATA_DIR
from .metrics import exit_breakdown, markdown_table
from .plots import equity_chart


def data_fingerprint(ticker: str) -> str:
    """Download date and SHA-256 of the cached CSV, so anyone can check they
    have exactly the same prices (Yahoo revises adjusted prices over time)."""
    path = DATA_DIR / f"{ticker}.csv"
    digest = hashlib.sha256(path.read_bytes()).hexdigest()[:16]
    downloaded = dt.datetime.fromtimestamp(path.stat().st_mtime).date()
    return f"`{path.name}` downloaded {downloaded}, sha256 `{digest}…`"


def write_results(out_dir: Path, title: str, period: str, strategy_net: pd.Series,
                  benchmark_net: pd.Series, rows: dict, notes: list[str],
                  trades: pd.DataFrame | None = None, extra_md: str = "") -> None:
    """Write results.md, equity_drawdown.png and (if given) trades.csv into out_dir."""
    out_dir.mkdir(parents=True, exist_ok=True)
    equity_chart(strategy_net, benchmark_net, out_dir / "equity_drawdown.png",
                 f"{title}, {period}: strategy vs buy & hold")

    lines = [f"# {title}: {period}", "",
             f"Period measured: {strategy_net.index[0].date()} to {strategy_net.index[-1].date()}",
             ""]
    lines += [f"- {note}" for note in notes]
    lines += ["", "## Performance", "", markdown_table(rows), "",
              "![Equity and drawdown](equity_drawdown.png)", ""]
    if trades is not None:
        trades.to_csv(out_dir / "trades.csv", index=False)
        gaps = trades[trades["crosses_gap"]]
        lines += ["## Trades", "",
                  f"All {len(trades)} trades are in [trades.csv](trades.csv). "
                  f"Trades open across a data gap: {len(gaps)}.", ""]
        if not gaps.empty:
            lines += ["```", gaps.to_string(index=False), "```", ""]
        lines += [breakdown_markdown(trades), ""]
    if extra_md:
        lines += [extra_md, ""]
    lines += [f"_Generated by `run.py --period {period}` on {dt.date.today()}._", ""]
    (out_dir / "results.md").write_text("\n".join(lines))


def breakdown_markdown(trades: pd.DataFrame) -> str:
    """'Why trades ended' as a markdown table (closed trades only)."""
    table = exit_breakdown(trades)
    lines = ["### Why trades ended (closed trades)", "",
             "| Exit | Trades | Win rate | Avg return | Sum of returns |",
             "|---|---:|---:|---:|---:|"]
    for reason, r in table.iterrows():
        lines.append(f"| {reason} | {int(r['trades'])} | {r['win_rate']:.1%} | "
                     f"{r['avg_return']:+.2%} | {r['sum_of_returns']:+.2f} |")
    return "\n".join(lines)
